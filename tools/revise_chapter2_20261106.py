def duration(value):
    if isinstance(value,str):return re.sub(r'(?<=[0-9０-９])月', 'か月',value)
    if isinstance(value,list):return [duration(v) for v in value]
    if isinstance(value,dict):return {k:duration(v) for k,v in value.items()}
    return value
